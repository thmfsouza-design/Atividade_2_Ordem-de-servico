create extension if not exists pgcrypto;

create table if not exists public.clientes (
    id uuid primary key default gen_random_uuid(),
    nome text not null check (length(btrim(nome)) between 2 and 120),
    email text not null unique,
    celular varchar(11) not null,
    criado_em timestamptz not null default now(),
    constraint clientes_email_formato check (
        email = lower(btrim(email))
        and email ~ '^[a-z0-9._%+-]+@[a-z0-9.-]+\.[a-z]{2,}$'
    ),
    constraint clientes_celular_formato check (celular ~ '^[0-9]{10,11}$')
);

create table if not exists public.ordens_servico (
    id bigint generated by default as identity primary key,
    cliente_id uuid not null references public.clientes(id) on delete restrict,
    equipamento text not null check (length(btrim(equipamento)) between 2 and 120),
    problema text not null check (length(btrim(problema)) between 5 and 2000),
    observacoes text not null default '',
    status text not null default 'Aberto',
    criado_em timestamptz not null default now(),
    atualizado_em timestamptz not null default now(),
    constraint ordens_servico_status_valido check (
        status in ('Aberto', 'Em análise', 'Aguardando peça', 'Concluído', 'Entregue')
    )
);

create index if not exists ordens_servico_cliente_id_idx
    on public.ordens_servico (cliente_id);
create index if not exists ordens_servico_status_idx
    on public.ordens_servico (status);
create index if not exists ordens_servico_criado_em_idx
    on public.ordens_servico (criado_em desc);

create or replace function public.marcar_ordem_atualizada()
returns trigger
language plpgsql
as $$
begin
    new.atualizado_em = now();
    return new;
end;
$$;

drop trigger if exists ordens_servico_atualizado_em on public.ordens_servico;
create trigger ordens_servico_atualizado_em
before update on public.ordens_servico
for each row execute function public.marcar_ordem_atualizada();

alter table public.clientes enable row level security;
alter table public.ordens_servico enable row level security;

